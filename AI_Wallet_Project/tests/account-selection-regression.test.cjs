'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const context={window:{}};vm.createContext(context);
for(const file of ['accounts.js','billing.js'])vm.runInContext(fs.readFileSync(path.join(__dirname,'../src/modules',file),'utf8'),context,{filename:file});
const {accounts,billing}=context.window.AIWalletModules;
const profiles=[{id:'a',serviceId:'chatgpt',cost:120,billingCycle:'yearly'},{id:'b',serviceId:'claude',cost:15,billingCycle:'monthly'}];
assert.equal(accounts.resolveActive(profiles,'a','chatgpt').id,'a');
assert.equal(accounts.resolveActive(profiles,'a','claude').id,'b','Must never show another provider account');
assert.equal(accounts.resolveActive(profiles,'a','gemini'),null,'Provider with no profiles must remain empty');
assert.equal(accounts.resolveActive(profiles,'','claude').id,'b');
assert.equal(accounts.resolveActive([],null,'chatgpt'),null);
assert.equal(billing.summarize(profiles).monthly,25);
const app=fs.readFileSync(path.join(__dirname,'../src/app.js'),'utf8');
assert.match(app,/selectedAccount=a\?\.id\|\|'';render\(\)/,'Switching providers must clear a stale account');
assert.match(app,/billing\.summarize\(state\.accounts\)\.monthly/,'Home total must use billing engine');
console.log('DomAIn provider switching and subscription totals passed.');
