'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const app=fs.readFileSync(path.join(__dirname,'../src/app.js'),'utf8');
const storage=fs.readFileSync(path.join(__dirname,'../src/modules/storage.js'),'utf8');
assert.match(app,/const \{data,\.\.\.metadata\}=file;\s*return \{\.\.\.metadata,id:fileIdMap\.get\(file\.id\)\|\|id\(\)\}/,'Imported file payload must not be copied to localStorage');
assert.match(app,/const incompleteFiles=parsed\.files\.filter\(file=>file\.data==null&&file\.storageMode!=='remote'\)/,'Incomplete backups must be detected');
assert.match(app,/if\(!confirm\(\x60Replace this device/,'Missing file contents require confirmation');
assert.match(storage,/tx\.oncomplete=\(\)=>resolve\(keys\)/,'File audit must wait for completed IndexedDB transaction');
assert.match(storage,/tx\.onabort=\(\)=>reject\(/,'File audit must reject aborted transactions');
assert.match(app,/let backupExportBusy=false;async function exportBackup\(\)/,'Backup export must guard concurrent work');
assert.match(app,/finally\{backupExportBusy=false\}/,'Backup export must release its lock');
assert.match(app,/if\(localFileOperationBusy\(\)\|\|driveLibraryBusy\)/,'Backup import must wait for other file operations');
assert.match(app,/if\(localFileOperationBusy\(\)\|\|driveLibraryBusy\)/,'Uploads must wait for backup export');
assert.match(app,/toast\('Backup import cancelled'\);\s*return/,'User cancellation must not report invalid backup');
assert.match(app,/a\.download='domain-backup\.json'/,'Export filename must use DomAIn brand');
assert.match(app,/if\(previous\)state=previous/,'Rollback must restore in-memory metadata when persistence fails');
console.log('DomAIn backup import and IndexedDB integrity regression checks passed.');
