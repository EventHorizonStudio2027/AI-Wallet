'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const source=fs.readFileSync(path.join(__dirname,'../src/app.js'),'utf8');
const start=source.indexOf("$('#driveRestoreBtn').onclick");
assert.ok(start>=0,"recovery handler must exist");
const handler=source.slice(start,source.indexOf("\ndriveControls();",start));
assert.ok(handler.length>1000,'recovery handler must exist');
assert.match(handler,/domain-backup-\[0-9T-Z-\]/,'only expected backup names should be restored');
assert.match(handler,/Number\.isSafeInteger\(Number\(latest\.size\)\)/,'metadata size must be safe integer');
assert.match(handler,/String\(a\.id\|\|''\)\.localeCompare/,'timestamp ties must be deterministic');
assert.match(handler,/Your existing domAIn data was not changed/,'recovery should remain non-destructive');
const html=fs.readFileSync(path.join(__dirname,'../index.html'),'utf8');
assert.match(html,/id="driveRestoreBtn"[^>]*>Download verified backup<\/button>/,'recovery action must be clearly labeled');
assert.match(handler,/No domAIn backups found yet\. Use Save backup to Drive first/,'empty backup list must give next action');
assert.match(handler,/Verified backup downloaded: /,'success must identify downloaded file');
assert.match(handler,/parsed\.files\.some\(file=>file\.data==null\).*missing file contents/);
console.log('Drive recovery guard checks passed');
