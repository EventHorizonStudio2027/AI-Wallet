const assert=require('node:assert/strict');const fs=require('node:fs'),vm=require('node:vm');
const store=new Map();const window={localStorage:{getItem:k=>store.get(k)||null,setItem:(k,v)=>store.set(k,v)}};
vm.runInNewContext(fs.readFileSync('src/modules/reminders.js','utf8'),{window});
const r=window.AIWalletModules.reminders;
const a={id:'test',label:'Studio',trialEnabled:true,trialStatus:'active',trialEnd:'2026-11-20',cancelBy:'2026-11-18',renewalDate:'2026-11-20',cost:20,billingCycle:'monthly',alertDays:3};
assert.equal(r.entries([a],'2026-11-16',r.prefs()).length,2);
assert.equal(r.entries([{...a,trialStatus:'cancelled'}],'2026-11-16',r.prefs()).length,1);
assert.equal(r.dateDays('2026-02-30','2026-02-28'),null);
assert.equal(r.dateDays('2026-11-18','2026-11-16'),2);
const p=r.snooze(r.prefs(),'test:trial_cancel:2026-11-18','2026-11-17');assert.equal(r.entries([a],'2026-11-16',p).length,1);
assert.equal(r.entries([a],'2026-11-18',p).length,2);
assert.equal(r.entries([a],'2026-11-16',{enabled:false}).length,0);
assert.equal(r.entries([{...a,renewalDate:'bad',trialEnabled:false}],'2026-11-16',r.prefs()).length,0);
assert.equal(r.entries([{...a,trialEnabled:false,renewalDate:'2026-11-18'}],'2026-11-16',r.prefs()).length,1);
assert.equal(r.nextDay('2026-12-31'),'2027-01-01');
assert.equal(r.nextDay('2028-02-28'),'2028-02-29');
assert.throws(()=>r.nextDay('2026-02-30'),/Invalid reminder date/);
const snoozed=r.snooze(r.prefs(),'test:trial_cancel:2026-11-18',r.nextDay('2026-11-16'));
assert.equal(r.entries([a],'2026-11-16',snoozed).length,1);
assert.equal(r.entries([a],'2026-11-17',snoozed).length,1);
assert.equal(r.entries([a],'2026-11-18',snoozed).length,2);
assert.equal(Object.keys(r.prefs({muted:{'a:renewal:2026-11-18':'2026-02-30'}}).muted).length,0);
console.log('Reminder domain tests passed');
