'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const context={window:{},console,Date,Set,Map};
context.window.AIWalletModules={};
vm.createContext(context);
for(const file of ['billing.js','payment-forecast.js','creator.js','backup.js']){
 const code=fs.readFileSync(path.join(__dirname,'../src/modules',file),'utf8');
 vm.runInContext(code,context,{filename:file});
}
const {billing,paymentForecast,creator,backup}=context.window.AIWalletModules;
assert.equal(billing.monthlyEquivalent(120,'yearly'),10);
assert.equal(billing.monthlyEquivalent(12,'weekly'),52);
assert.equal(billing.monthlyEquivalent(true,'monthly'),0);
assert.equal(billing.monthlyEquivalent('','monthly'),0);
assert.equal(billing.monthlyEquivalent(Infinity,'monthly'),0);
assert.equal(billing.daysUntil('2026-02-30','2026-02-01'),null);
assert.equal(billing.nextRenewalDate('2026-01-31','monthly','2026-02-01'),'2026-02-28');
assert.equal(billing.nextRenewalDate('2026-01-31','monthly','2026-03-01'),'2026-03-31');
assert.equal(billing.nextRenewalDate('2024-02-29','yearly','2025-01-01'),'2025-02-28');
assert.equal(billing.nextRenewalDate('2026-01-01','weekly','2026-01-09'),'2026-01-15');
const account={id:'a1',label:'Test',cost:12,billingCycle:'monthly',renewalDate:'2026-01-31'};
const forecast=paymentForecast.summary([account],'2026-02-01',65);
assert.deepEqual(Array.from(forecast.events.map(e=>e.date)),['2026-02-28','2026-03-31']);
assert.equal(forecast.total,24);
assert.equal(paymentForecast.summary([{...account,cost:true}],'2026-02-01',65).total,0);
const trial={...account,trialEnabled:true,trialStatus:'active',trialEnd:'2026-02-08',cancelBy:'2026-02-05',alertDays:7};
const alerts=billing.alerts([trial],'2026-02-01');
assert.equal(alerts.some(e=>e.type==='trial_cancel'),true);
assert.equal(alerts.some(e=>e.type==='trial_end'),true);
assert.equal(alerts.some(e=>e.type==='renewal'),false);
assert.equal(creator.monthlyRecurring([{status:'active',cadence:'quarterly',amount:300}]),100);
assert.equal(creator.report({goal:1000,agreements:[],payouts:[{id:'p',client:'Client',amount:250,dueDate:'2026-02-10',status:'pending'}]},'2026-02-01').outstanding,250);
const valid={schemaVersion:7,services:[],accounts:[],files:[]};
assert.equal(backup.validateBackup(valid).fileCount,0);
assert.throws(()=>backup.validateBackup({...valid,files:[{id:'a',name:'file',data:'data:text/plain;base64,%%%%'}]}),/Invalid file data/);
console.log('DomAIn financial, subscription, trial and backup regression tests passed.');
