'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const src=fs.readFileSync(path.join(__dirname,'../src/app.js'),'utf8');
const start=src.indexOf('function shiftResetDate(');
const end=src.indexOf('function localDateKey(',start);
assert.ok(start>=0&&end>start,'date helper found');
const context=vm.createContext({Date});
vm.runInContext(src.slice(start,end),context);
const shift=context.shiftResetDate;
assert.equal(shift('2024-01-31','monthly'),'2024-02-29');
assert.equal(shift('2025-01-31','monthly'),'2025-02-28');
assert.equal(shift('2024-02-29','yearly'),'2025-02-28');
assert.equal(shift('2025-02-30','monthly'),'');
assert.equal(shift('2025-13-01','monthly'),'');
assert.equal(shift('2025-01-01','weekly'),'2025-01-08');
const account=src.slice(src.indexOf("$('#accountForm').onsubmit="),src.indexOf('function openChatMemory('));
assert.match(account,/A free plan cannot have a subscription charge/);
assert.match(account,/!shiftResetDate\(\$\('#aReset'\)\.value,'daily'\)/);
console.log('Calendar date calculations and billing guard checks passed');
